#!/usr/bin/env python3
"""Concatenate experiments/wokwi/*.h and sketch.ino into ONE file (sketch_single.ino) so only two files need pasting into Wokwi.
Run from the repository root. Reads experiments/wokwi/, writes only experiments/wokwi_single/."""
import re
W = 'experiments/wokwi/'
rd = lambda f: re.sub(r'#include "[^"]+"\n', '', open(W + f).read())
out = '// GENERATED by experiments/wokwi_single/make_single.py from experiments/wokwi/*. Do not edit.\n' + ''.join(f'\n// ===== {f} =====\n' + rd(f) for f in ('force_lut_table.h', 'reflex_model.h', 'scenarios.h', 'sketch.ino'))
open('experiments/wokwi_single/sketch_single.ino', 'w').write(out)
open('experiments/wokwi_single/diagram.json', 'w').write(open(W + 'diagram.json').read())
