#!/usr/bin/env python3
"""V2: concatenate experiments/wokwi/*.h and sketch.ino (time-based watchdog model) into ONE file for Wokwi.
Run from the repo root. Writes only experiments/wokwi_single_v2/ (the earlier experiments/wokwi_single/ is left as is)."""
import re
W = 'experiments/wokwi/'
rd = lambda f: re.sub(r'#include "[^"]+"\n', '', open(W + f).read())
out = '// GENERATED by experiments/wokwi_single_v2/make_single_v2.py from experiments/wokwi/* (time-based watchdog). Do not edit.\n' + ''.join(f'\n// ===== {f} =====\n' + rd(f) for f in ('force_lut_table.h', 'reflex_model.h', 'scenarios.h', 'sketch.ino'))
open('experiments/wokwi_single_v2/sketch_single.ino', 'w').write(out)
open('experiments/wokwi_single_v2/diagram.json', 'w').write(open(W + 'diagram.json').read())
