#!/usr/bin/env python3
"""Pin-assignment checker for constraints/de2_115.qsf (no guessing: the only source of FPGA pin names is a reference file you supply).

  python3 tools/check_pins.py                                   # structural checks only -> prints "NOT VERIFIED AGAINST THE BOARD"
  python3 tools/check_pins.py --reference DE2_115.qsf           # + every pin compared with Terasic's own file (System CD / terasic.com.tw)
  python3 tools/check_pins.py --reference DE2_115.qsf --emit constraints/de2_115_from_reference.qsf   # write a QSF whose pins ALL come from that file
Structural checks: every bit of every top-level port has a location, no pin used twice, no assignment to a missing port bit.
Exit status 1 on a mismatch / duplicate / unknown port bit. Unassigned ports or an unverified file are reported but only fail with --strict."""
import argparse, json, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LOC = re.compile(r"^\s*set_location_assignment\s+(PIN_\w+)\s+-to\s+(\S+)", re.M)

def top_ports(text):
    """-> {port: width} from the module header of de2_115_top (ANSI style)."""
    hdr = text[text.index(") (") :]; hdr = hdr[: hdr.index(");")]
    ports = {}
    for m in re.finditer(r"(input|output)\s+wire\s*(\[(\d+):(\d+)\])?\s*(\w+)", hdr): ports[m.group(5)] = (int(m.group(3)) - int(m.group(4)) + 1) if m.group(2) else 1
    return ports

def bits(ports): return {f"{p}[{i}]" if w > 1 else p for p, w in ports.items() for i in range(w)}
def locations(text): return [(m.group(2), m.group(1)) for m in LOC.finditer(re.sub(r"#.*", "", text))]
def read_map(path):
    m = {}
    for ln in open(path):
        ln = ln.split("#", 1)[0].strip()
        if ln: k, v = [x.strip() for x in ln.split("=")]; m[k] = v
    return m

def check(qsf_text, ports, ref_text=None, gpio_map=None):
    rep = dict(errors=[], unassigned=[], verified=[], unverified=[], mismatches=[])
    locs = locations(qsf_text); want = bits(ports); seen = {}
    for sig, pin in locs:
        if sig not in want: rep["errors"].append(f"assignment to unknown port bit {sig}")
        if pin in seen and seen[pin] != sig: rep["errors"].append(f"{pin} assigned to both {seen[pin]} and {sig}")
        seen.setdefault(pin, sig)
    mine = {s: p for s, p in locs}
    rep["unassigned"] = sorted(b for b in want if b not in mine)
    if ref_text is not None:
        ref = {s: p for s, p in locations(ref_text)}; gpio_map = gpio_map or {}
        for sig, pin in sorted(mine.items()):
            rsig = gpio_map.get(sig, sig); rp = ref.get(rsig)
            if rp is None: rep["unverified"].append(f"{sig}: '{rsig}' not found in the reference file")
            elif rp == pin: rep["verified"].append(f"{sig} = {pin} (reference {rsig})")
            else: rep["mismatches"].append(f"{sig}: file says {pin}, reference {rsig} says {rp}")
    else: rep["unverified"] = sorted(mine)
    return rep

def emit(ports, ref_text, gpio_map):
    ref = {s: p for s, p in locations(ref_text)}; out = ["# Generated by tools/check_pins.py: EVERY pin below was copied from the supplied reference file. Review before use.", ""]
    miss = []
    for b in sorted(bits(ports), key=lambda x: (re.sub(r"\[.*", "", x), int((re.search(r"\[(\d+)\]", x) or [0, 0])[1]) if "[" in x else 0)):
        r = gpio_map.get(b, b)
        if r in ref: out.append(f"set_location_assignment {ref[r]} -to {b}   ;# {r}")
        else: miss.append(b)
    return "\n".join(out) + "\n", miss

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--qsf", default=os.path.join(ROOT, "constraints", "de2_115.qsf")); ap.add_argument("--rtl", default=os.path.join(ROOT, "rtl", "de2_115_top.v"))
    ap.add_argument("--map", default=os.path.join(ROOT, "constraints", "gpio_map.txt")); ap.add_argument("--reference"); ap.add_argument("--emit"); ap.add_argument("--strict", action="store_true")
    ap.add_argument("--json", default=os.path.join(ROOT, "results", "pin_check.json"))
    a = ap.parse_args(argv)
    with open(a.rtl) as fh: ports = top_ports(fh.read())
    with open(a.qsf) as fh: q = fh.read()
    gm = read_map(a.map) if os.path.exists(a.map) else {}
    ref = None
    if a.reference:
        with open(a.reference) as fh: ref = fh.read()
    rep = check(q, ports, ref, gm); rep["reference_supplied"] = bool(a.reference)
    if a.emit:
        if ref is None: print("--emit needs --reference", file=sys.stderr); return 2
        txt, miss = emit(ports, ref, gm)
        with open(a.emit, "w") as fh: fh.write(txt)
        print(f"wrote {a.emit}; ports with no counterpart in the reference: {miss or 'none'}"); rep["emit_missing"] = miss
    status = "FAILED" if rep["errors"] or rep["mismatches"] else ("VERIFIED AGAINST REFERENCE" if a.reference and not rep["unverified"] and not rep["unassigned"] else "NOT VERIFIED AGAINST THE BOARD")
    rep["status"] = status
    os.makedirs(os.path.dirname(a.json), exist_ok=True)
    with open(a.json, "w") as fh: json.dump(rep, fh, indent=1, sort_keys=True)
    print(f"pin check: {status}; ports={len(bits(ports))} bits, unassigned={len(rep['unassigned'])}, verified={len(rep['verified'])}, unverified={len(rep['unverified'])}, mismatches={len(rep['mismatches'])}, errors={len(rep['errors'])}")
    for e in rep["errors"] + rep["mismatches"]: print("  ERROR:", e)
    if rep["unassigned"]: print("  UNASSIGNED (Quartus would place these on arbitrary pins!):", ", ".join(rep["unassigned"]))
    return 1 if (rep["errors"] or rep["mismatches"] or (a.strict and status != "VERIFIED AGAINST REFERENCE")) else 0

if __name__ == "__main__": sys.exit(main())
